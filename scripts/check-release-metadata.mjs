import assert from 'node:assert/strict'
import { access, readFile } from 'node:fs/promises'

const metadata = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'))
const decision = JSON.parse(await readFile(new URL('../decision.json', import.meta.url), 'utf8'))

assert.equal(metadata.name, '@stackline/once')
assert.equal(metadata.version, '1.0.0')
assert.equal(metadata.license, 'ISC')
assert.equal(metadata.engines.node, '>=0.10.0')
assert.equal(metadata.repository.url, 'git+https://github.com/alexandroit/stackline-once.git')
assert.equal(metadata.homepage, 'https://alexandro.net/docs/vanilla/once/')
assert.equal(metadata.publishConfig.access, 'public')
assert.equal(decision.package, 'once')
assert.equal(decision.target, metadata.name)
assert.equal(decision.targetVersion, metadata.version)
assert.equal(decision.decision, 'GO')
assert.equal(decision.canonicalState, 'PUBLISHED')
assert.equal(decision.reasonCode, 'UNPUBLISHED_TAGGED_API_FIX_WITH_BOUNDED_LEGACY_CJS_SURFACE_AND_TWO_QUALIFIED_DIRECT_ADOPTION_PATHS')
assert.equal(decision.publication.sourceCommit, 'ea00ab9a1ca2badbdfddaeb9236fb689fd064067')
assert.equal(decision.publication.artifactSha256, 'dd95a3455ed26d3e40c8d6fe107662b4475addf4ca6a6ef9fdb1b130ab3e1880')
assert.equal(decision.publication.npmPublished, true)
assert.equal(decision.publication.githubRepositoryCreated, true)
assert.equal(decision.publication.githubReleaseImmutable, true)
assert.equal(decision.publication.documentationPublished, true)
assert.equal(decision.publication.outreachCreated, true)
assert.equal(decision.publication.releaseDebt, null)
assert.equal(decision.adoptionOutcome.coverage, 'COMPLETE')
assert.equal(decision.adoptionOutcome.differentRepositoryCheck, 'PASS')
assert.equal(decision.adoptionOutcome.activeReleaseCheckpoint, null)

await Promise.all(metadata.files.map((filename) => access(new URL(`../${filename}`, import.meta.url))))
console.log('Frozen GO decision, immutable published state, metadata, adoption coverage, and package inventory passed.')
